@dataclass
class CandidateEvaluationSummary:
    """Summary metrics for a specific candidate generation strategy."""

    strategy_name: str
    total_evaluated: int
    linguistic_composite: float
    punctuation_adherence: float
    casing_fidelity: float
    lexical_overlap: float
    embedding_similarity: float
    behavioral_composite: float
    behavioral_mae: float
    judge_overall: float
    judge_voice: float
    judge_style: float
    judge_behavior: float
    judge_situation: float
    judge_epistemic: float
    failure_rate: float
    top_failures: Dict[str, int]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "strategy_name": self.strategy_name,
            "total_evaluated": self.total_evaluated,
            "linguistic_composite": round(self.linguistic_composite, 4),
            "punctuation_adherence": round(self.punctuation_adherence, 4),
            "casing_fidelity": round(self.casing_fidelity, 4),
            "lexical_overlap": round(self.lexical_overlap, 4),
            "embedding_similarity": round(self.embedding_similarity, 4),
            "behavioral_composite": round(self.behavioral_composite, 4),
            "behavioral_mae": round(self.behavioral_mae, 4),
            "judge_overall": round(self.judge_overall, 2),
            "judge_voice": round(self.judge_voice, 2),
            "judge_style": round(self.judge_style, 2),
            "judge_behavior": round(self.judge_behavior, 2),
            "judge_situation": round(self.judge_situation, 2),
            "judge_epistemic": round(self.judge_epistemic, 2),
            "failure_rate": round(self.failure_rate, 4),
            "top_failures": self.top_failures,
        }


class EvaluationEngine:
    """
    Master Evaluation Engine for Stages T035 - T040.
    """

    def __init__(
        self,
        embedding_engine: Optional[EmbeddingEngine] = None,
        linguistic_evaluator: Optional[LinguisticEvaluator] = None,
        behavioral_evaluator: Optional[BehavioralEvaluator] = None,
        failure_analyzer: Optional[FailureAnalyzer] = None,
    ):
        self.embedding_engine = embedding_engine or EmbeddingEngine()
        self.linguistic = linguistic_evaluator or LinguisticEvaluator(embedding_engine=self.embedding_engine)
        self.behavioral = behavioral_evaluator or BehavioralEvaluator()
        self.failure = failure_analyzer or FailureAnalyzer()

    def evaluate_strategy(
        self,
        strategy_name: str,
        candidates: Sequence[str],
        targets: Sequence[str],
        contexts: Optional[Sequence[str]] = None,
    ) -> Tuple[CandidateEvaluationSummary, Dict[str, Any]]:
        """
        Evaluate a set of candidate responses generated by a given strategy against targets.
        """
        n = len(candidates)
        if n != len(targets):
            raise ValueError(f"Candidate count ({n}) must match target count ({len(targets)})")

        ctxs = list(contexts) if contexts else [""] * n

        # 1. Linguistic similarity evaluation (T036)
        ling_res = self.linguistic.evaluate_batch(candidates, targets, contexts=ctxs)

        # 2. Behavioral evaluation (T037)
        behav_res = self.behavioral.evaluate_batch(candidates, targets=targets)

        # 3. Deterministic Judge evaluation (T038 & T039)
        judge_results: List[JudgeEvaluationResult] = []
        for c, t, ctx in zip(candidates, targets, ctxs):
            j_res = DeterministicJudge.evaluate(real_response=t, candidate_response=c, context=ctx)
            judge_results.append(j_res)

        j_overall = float(np.mean([j.overall_score for j in judge_results]))
        j_voice = float(np.mean([j.voice_authenticity for j in judge_results]))
        j_style = float(np.mean([j.stylistic_adherence for j in judge_results]))
        j_behav = float(np.mean([j.behavioral_consistency for j in judge_results]))
        j_sit = float(np.mean([j.situational_appropriateness for j in judge_results]))
        j_epist = float(np.mean([j.epistemic_grounding for j in judge_results]))

        # 4. Failure analysis (T040)
        fail_report = self.failure.analyze_batch(candidates, targets=targets, contexts=ctxs)

        summary = CandidateEvaluationSummary(
            strategy_name=strategy_name,
            total_evaluated=n,
            linguistic_composite=ling_res["mean_composite_score"],
            punctuation_adherence=ling_res["means"]["punctuation_score"],
            casing_fidelity=ling_res["means"]["casing_score"],
            lexical_overlap=ling_res["means"]["lexical_jaccard"],
            embedding_similarity=ling_res["means"]["embedding_similarity"],
            behavioral_composite=behav_res["mean_composite_score"],
            behavioral_mae=behav_res["mean_mae"],
            judge_overall=j_overall,
            judge_voice=j_voice,
            judge_style=j_style,
            judge_behavior=j_behav,
            judge_situation=j_sit,
            judge_epistemic=j_epist,
            failure_rate=fail_report.failure_rate,
            top_failures=dict(sorted(fail_report.error_counts.items(), key=lambda x: x[1], reverse=True)[:5]),
        )

        full_details = {
            "linguistic": ling_res,
            "behavioral": behav_res,
            "judge": [j.to_dict() for j in judge_results],
            "failure_report": fail_report.to_dict(),
        }

        return summary, full_details

    def generate_markdown_report(
        self,
        summaries: Sequence[CandidateEvaluationSummary],
        output_path: Optional[Path] = None,
    ) -> str:
        """
        Generate a comprehensive markdown summary comparing evaluated strategies.
        """
        lines = [
            "# Persona Engine: Comprehensive Evaluation Report (T035 – T040)",
            "",
            f"**Generated**: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}  ",
            f"**Total Test Pairs Evaluated**: {summaries[0].total_evaluated if summaries else 0}  ",
            "",
            "---",
            "",
            "## 1. Comparative Performance Matrix",
            "",
            "| Metric Dimension | " + " | ".join(s.strategy_name for s in summaries) + " |",
            "| :--- | " + " | ".join([":---:"] * len(summaries)) + " |",
            "| **Composite Linguistic Score** | " + " | ".join(f"**{s.linguistic_composite:.4f}**" for s in summaries) + " |",
            "| Punctuation Adherence (Drop Rate) | " + " | ".join(f"{s.punctuation_adherence:.4f}" for s in summaries) + " |",
            "| Casing Fidelity | " + " | ".join(f"{s.casing_fidelity:.4f}" for s in summaries) + " |",
            "| Lexical Jaccard Overlap | " + " | ".join(f"{s.lexical_overlap:.4f}" for s in summaries) + " |",
            "| 768-dim Embedding Similarity | " + " | ".join(f"{s.embedding_similarity:.4f}" for s in summaries) + " |",
            "| **Composite Behavioral Score** | " + " | ".join(f"**{s.behavioral_composite:.4f}**" for s in summaries) + " |",
            "| Behavioral MAE Error (lower is better) | " + " | ".join(f"{s.behavioral_mae:.4f}" for s in summaries) + " |",
            "| **LLM-as-Judge Overall (1-5)** | " + " | ".join(f"**{s.judge_overall:.2f} / 5.0**" for s in summaries) + " |",
            "| - Voice Authenticity | " + " | ".join(f"{s.judge_voice:.2f}" for s in summaries) + " |",
            "| - Stylistic Adherence | " + " | ".join(f"{s.judge_style:.2f}" for s in summaries) + " |",
            "| - Behavioral Consistency | " + " | ".join(f"{s.judge_behavior:.2f}" for s in summaries) + " |",
            "| - Situational Register | " + " | ".join(f"{s.judge_situation:.2f}" for s in summaries) + " |",
            "| - Epistemic & Anti-Hallucination | " + " | ".join(f"{s.judge_epistemic:.2f}" for s in summaries) + " |",
            "| **Failure Rate (%)** | " + " | ".join(f"**{s.failure_rate * 100:.1f}%**" for s in summaries) + " |",
            "",
            "---",
            "",
            "## 2. Failure Mode Breakdown",
            "",
        ]

        for s in summaries:
            lines.append(f"### Strategy: `{s.strategy_name}`")
            lines.append(f"- **Overall Failure Rate**: {s.failure_rate * 100:.1f}%")
            if s.top_failures:
                lines.append("- **Top Error Categories**:")
                for err, cnt in s.top_failures.items():
                    lines.append(f"  - `{err}`: {cnt} occurrences")
            else:
                lines.append("- **No systematic errors detected**")
            lines.append("")

        report_str = "\n".join(lines)
        if output_path:
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(report_str, encoding="utf-8")

        return report_str
